"""공휴일 — 결근 판정에서 빼고, 그날 나온 사람에게 점수를 준다.

**왜 필요했나 (2026-08-18).** 2026-08-17(광복절 대체 휴일)에 안 나온 사람들이
전부 **결근으로 찍혔다.** 판정이 `근무 요일인가`만 보고 있어서 공휴일이 낄
자리가 없었다 — 월요일이 근무일인 사람에게 대체공휴일은 그냥 결근일이었다.

**라이브러리로 계산한다.** 공공데이터포털(한국천문연구원) API 는 키가 필요하고
**호출이 실패하면 결근 판정이 통째로 흔들린다** — 결근은 급여·점수로 이어지는
값이라 바깥에 기대면 안 된다. `holidays` 는 오프라인에서 음력(설·추석)과
대체공휴일까지 계산한다.

    2026-08-15 광복절 · 2026-08-17 광복절 대체 휴일
    2026-09-24~26 추석 · 2026-10-05 개천절 대체 휴일

**회사 자체 휴무일(창립기념일 등)은 아직 없다.** 생기면 [_EXTRA] 에 넣거나
DB 표로 빼면 된다 — 부르는 쪽은 이 파일의 함수만 쓴다.
"""

from __future__ import annotations

from datetime import date

import holidays as _holidays

#: 대한민국 관공서 공휴일. 조회할 때 그 해를 알아서 채운다.
_KR = _holidays.country_holidays("KR")

#: 법정 공휴일이 아닌 회사 자체 휴무일 — 아직 없다.
#: 넣을 때는 `{date(2026, 3, 2): "창립기념일"}` 모양으로 둔다.
_EXTRA: dict[date, str] = {}


def is_holiday(day: date) -> bool:
    """그날이 쉬는 날인가 (법정 공휴일 + 회사 휴무일).

    **주말은 여기 안 들어간다.** 토·일은 사람마다 다른 `work_days` 가 정하는
    것이라, 여기서 같이 묶으면 주말에 일하는 사람의 근무일이 사라진다.
    """
    return day in _EXTRA or day in _KR


def holiday_name(day: date) -> str | None:
    """`광복절 대체 휴일` — 아니면 None. 알림·로그에 쓴다."""
    return _EXTRA.get(day) or _KR.get(day)
