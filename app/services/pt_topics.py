"""PT 만족도 폼의 **객관식 항목표** (2026-09-16).

## 왜 객관식인가

예전에는 `바라는 점` 서술형 한 칸이었는데 **"좋아요~" 만 쌓였다.**
우리가 알아야 하는 것은 *이 트레이너의 무엇이* 좋았고 아쉬웠는지인데,
빈 칸을 주면 사람은 제일 짧은 말로 답한다.

그래서 **주제를 먼저 고르게 하고**, 고른 자리에만 글칸을 연다.
글을 안 적어도 주제는 남으므로 **한 글자도 안 적은 답도 셀 수 있다.**

## 좋았던 점 · 보완할 점이 **같은 주제표**를 쓴다

말만 칭찬형(`praise`) · 요청형(`improve`)으로 갈린다. 주제가 갈리면
"식단은 칭찬 3 · 요청 5" 처럼 **한 축으로 세지 못한다** — 그러려고 만든 것이라
여기서 갈라지면 기능이 뜻을 잃는다.

## 표가 **서버에** 있는 이유

이 문구를 읽는 곳이 셋이다 — 회원이 보는 웹폼(`HiFIS-Client-V2`),
대표가 보는 앱, 그리고 저장. 세 곳에 각각 적으면 **문구를 고칠 때 반드시
하나를 빠뜨리고**, 앱은 스토어를 거쳐야 바뀐다.
그래서 웹폼도 앱도 **서버가 주는 표를 그린다.**

## 코드를 지우지 않는다

답에는 `code` 만 남고 문구는 읽을 때 붙인다. 코드를 지우면 **이미 낸 답의
문구가 사라진다** — 쓸 일이 없어지면 `RETIRED` 로 옮겨서 새 설문에만 안 뜨게 한다.
"""

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class PtTopic:
    """주제 하나 — 코드 · 칭찬형 문구 · 요청형 문구."""

    code: str
    praise: str
    improve: str


#: 화면에 뜨는 차례가 곧 이 차례다 — **회원이 훑는 순서**라 임의로 섞지 않는다.
#: 수업 중에 겪는 순서(자세 → 강도 → 설명 → 프로그램)를 앞에 두고,
#: 수업 밖의 것(식단 · 이끌어주기 · 태도 · 시간)을 뒤에 둔다.
PT_TOPICS: tuple[PtTopic, ...] = (
    PtTopic("POSTURE", "자세를 꼼꼼히 봐주셔요", "자세를 조금 더 봐주시면 좋겠어요"),
    PtTopic("INTENSITY", "운동 강도가 잘 맞아요", "운동 강도를 조절해주시면 좋겠어요"),
    PtTopic("EXPLAIN", "운동 방법을 쉽게 알려주셔요", "설명을 조금 더 자세히 해주시면 좋겠어요"),
    PtTopic("PROGRAM", "제 몸 상태에 맞게 짜주셔요", "제 몸 상태에 더 맞춰주시면 좋겠어요"),
    PtTopic("DIET", "식단 관리를 잘해주셔요", "식단 관리를 더 챙겨주시면 좋겠어요"),
    PtTopic("MOTIVATE", "동기부여가 돼요", "좀 더 이끌어주시면 좋겠어요"),
    PtTopic("MANNER", "친절하고 편해요", "조금 더 편하게 대해주시면 좋겠어요"),
    PtTopic("TIME", "시간 약속을 잘 지켜주셔요", "수업 시간을 잘 지켜주시면 좋겠어요"),
)

#: 새 설문에는 안 띄우지만 **옛 답을 읽을 때는 필요한** 주제.
#: 표에서 지우는 대신 여기로 옮긴다 (지우면 그 답의 문구가 사라진다).
RETIRED: tuple[PtTopic, ...] = ()

_BY_CODE = {t.code: t for t in (*PT_TOPICS, *RETIRED)}

#: 고른 주제마다 붙이는 글 — 짧게 받는다. 길게 받으면 다시 서술형이 된다
MAX_NOTE = 300


def is_known(code: str) -> bool:
    return code in _BY_CODE


def label_of(code: str, *, praise: bool) -> str:
    """그 주제의 문구 — **모르는 코드면 코드를 그대로 돌려준다.**

    화면이 빈칸으로 뜨는 것보다 낫다. 표에서 실수로 지웠을 때 눈에 띈다.
    """
    topic = _BY_CODE.get(code)
    if topic is None:
        return code
    return topic.praise if praise else topic.improve
