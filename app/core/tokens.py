"""회원에게 나가는 공개 주소의 토큰 (2026-08-20).

설문 QR · 매장 TV · PT 만족도 폼이 다 이걸 쓴다.

## 왜 `secrets.token_urlsafe` 를 안 쓰나

그건 16자에 `-` 와 `_` 가 섞인다 (`oMfQBvGmF8IPVt--`). 두 가지가 걸렸다.

| | |
|---|---|
| **문자로 보낼 때 의심받는다** | 낯선 도메인 + 알 수 없는 긴 문자열은 스팸 링크처럼 보인다 |
| **SMS 90바이트를 넘긴다** | 한글 안내 50바이트 + 옛 주소 37바이트 = 88. 한 글자만 더 붙어도 LMS 로 넘어가 요금이 두 배 반이 된다 |

## 지금 값

- **8자**, 소문자와 숫자만
- **헷갈리는 글자를 뺐다** — `0`·`o`, `1`·`l`·`i`.
  전화로 불러 주거나 손으로 옮겨 적는 일이 생긴다
- 조합 수 **31⁸ ≈ 8,500억**. 제출·조회에 분당 30회 제한이 걸려 있어
  하나씩 넣어 보는 건 사실상 불가능하다

**8자 밑으로 내리지 않는다** — 6자면 9억이라 눈에 띄게 얇아진다.

## 이미 나간 토큰

**길이를 바꿔도 옛 토큰은 그대로 산다** — 여기는 만드는 자리일 뿐이고
조회는 값을 그대로 맞춰 본다. 짧은 것으로 갈아 끼우려면 발급을 다시 한다
(`POST /branches/{id}/survey-link/reset`). **옛 QR 은 그 즉시 안 열린다.**
"""

import secrets

#: 헷갈리는 글자를 뺀 알파벳 — `0`·`o` · `1`·`l`·`i` 가 없다
ALPHABET = "23456789abcdefghjkmnpqrstuvwxyz"

#: 기본 길이 — 세 화면이 같은 값을 쓴다 (한쪽만 길면 문자 길이가 갈린다)
LENGTH = 8

#: 회원 수업 주소(`/training/{token}`) 길이 — 한 사람의 운동 기록 전부가 보이는
#: 주소라 더 길게 잡는다. 31¹² ≈ 8×10¹⁷
TRAINING_TOKEN_LENGTH = 12


def public_token(length: int = LENGTH) -> str:
    """회원에게 나가는 주소의 마지막 칸을 만든다."""
    return "".join(secrets.choice(ALPHABET) for _ in range(length))
