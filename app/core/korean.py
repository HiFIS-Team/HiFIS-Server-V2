"""조사 붙이기 — `클레임해결 이(가)` 처럼 보이던 것을 없앤다 (2026-09-09).

알림 제목과 오류 문구에 **지점이 지은 이름**이 들어간다. 환경정비 항목도
개인 업무 입력 칸도 사람이 만든 이름이라, 서버가 미리 알 수 없어서
`이(가)` · `을(를)` 처럼 두 개를 다 적어 두고 있었다. 실제로 폰에 그대로
떴다 — `클레임해결 이(가) 승인됐어요`.

**받침으로 가른다.** 한글 음절은 유니코드에서 `(초성, 중성, 종성)` 이 규칙적으로
배열돼 있어서, `(코드 - 가) % 28` 이 0이 아니면 받침이 있는 것이다.

한글이 아닌 이름(`TM`, `A동`)은 **가를 근거가 없다.** 그때만 예전처럼
둘 다 적는다 — 틀린 조사를 붙이는 것보다 낫다.
"""

#: 앞말에 받침이 있을 때 / 없을 때 — `josa` 가 받는 짝
_PAIRS = {
    "이": ("이", "가"),
    "가": ("이", "가"),
    "을": ("을", "를"),
    "를": ("을", "를"),
    "은": ("은", "는"),
    "는": ("은", "는"),
    "과": ("과", "와"),
    "와": ("과", "와"),
    #: `으로` 는 **ㄹ 받침이 예외다** — `블로그로` 가 아니라 `블로그로`,
    #: `사물로` 처럼 ㄹ 뒤에는 `로` 가 붙는다. `has_final` 만으로는 못 가른다
    "로": ("으로", "로"),
    "으로": ("으로", "로"),
}


def has_final(word: str) -> bool | None:
    """마지막 글자에 받침이 있나 — 한글이 아니면 `None` (알 수 없다)."""
    if not word:
        return None
    code = ord(word[-1])
    if not (0xAC00 <= code <= 0xD7A3):
        return None
    return (code - 0xAC00) % 28 != 0


def josa(word: str, kind: str) -> str:
    """`josa("클레임해결", "이")` → `클레임해결이`.

    [kind] 는 짝 중 아무거나 준다 (`이` 든 `가` 든 같은 짝을 가리킨다).
    """
    pair = _PAIRS.get(kind)
    if pair is None:
        return f"{word}{kind}"
    final = has_final(word)
    if final is None:
        return f"{word}{pair[0]}({pair[1]})"
    # ㄹ 받침은 `으로` 가 아니라 `로` 를 쓴다
    if pair == ("으로", "로") and final and (ord(word[-1]) - 0xAC00) % 28 == 8:
        return f"{word}로"
    return f"{word}{pair[0] if final else pair[1]}"
